export const getMoodConfig = (id: MoodId): MoodConfig | undefined =>
  MOODS.find(m => m.id === id);

export const getStatesForMood = (mood: MoodId): StateInfo[] =>
  STATES.filter(s => s.moods.includes(mood));

export const getSpotsForMoodAndState = (mood: MoodId, stateId: string): TourismSpot[] =>
  TOURISM_SPOTS.filter(s => s.stateId === stateId && s.moods.includes(mood));

export const getSpotsForMood = (mood: MoodId): TourismSpot[] =>
  TOURISM_SPOTS.filter(s => s.moods.includes(mood));
